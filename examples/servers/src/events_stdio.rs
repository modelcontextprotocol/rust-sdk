//! An anonymous Events server showing a check source with one sample event.

use std::sync::{Arc, OnceLock};

use rmcp::{
    ServerHandler, ServiceExt,
    events::{
        server::{CheckQuery, CheckedBatch, Descriptor, EventsServer},
        wire::{DeliveryMode, EventOccurrence},
    },
    model::JsonObject,
    transport::stdio,
};

struct Server(EventsServer);

impl ServerHandler for Server {
    fn events(&self) -> Option<&EventsServer> {
        Some(&self.0)
    }
}

#[tokio::main(flavor = "current_thread")]
async fn main() -> anyhow::Result<()> {
    let server = EventsServer::new();
    let sample_time = Arc::new(OnceLock::new());
    server.register_check(
        Descriptor::typed::<JsonObject, JsonObject>(
            "demo.sample",
            "A sample generated by the first replay request",
            [DeliveryMode::Poll],
        ),
        move |_, _, query: CheckQuery| {
            let sample_time = sample_time.clone();
            async move {
                Ok(match query.cursor.as_deref() {
                    None => CheckedBatch::new(if sample_time.get().is_some() {
                        "1"
                    } else {
                        "0"
                    }),
                    Some("0") => {
                        let time = *sample_time.get_or_init(chrono::Utc::now);
                        let mut batch = CheckedBatch::new("1");
                        if query.age_floor.is_some_and(|floor| time < floor) {
                            batch.start = Some("1".into());
                        } else {
                            batch.events.push(EventOccurrence::new(
                                "sample",
                                "demo.sample",
                                time,
                                JsonObject::new(),
                            ));
                        }
                        batch
                    }
                    Some("1") => CheckedBatch::new("1"),
                    _ => {
                        return Err(rmcp::events::wire::EventsError::InvalidParams(
                            "unknown cursor".into(),
                        ));
                    }
                })
            }
        },
    )?;
    Server(server).serve(stdio()).await?.waiting().await?;
    Ok(())
}
