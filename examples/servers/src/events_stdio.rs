//! An Events check source with one sample event.

use std::{future::ready, sync::OnceLock};

use rmcp::{
    ServerHandler, ServiceExt,
    events::{
        server::{CheckedBatch, Descriptor, EventsServer},
        wire::{DeliveryMode, EventOccurrence, EventsError},
    },
    model::JsonObject,
    transport::stdio,
};

struct Server(EventsServer);

impl ServerHandler for Server {
    fn events(&self) -> Option<&EventsServer> {
        Some(&self.0)
    }
}

#[tokio::main(flavor = "current_thread")]
async fn main() -> anyhow::Result<()> {
    let server = EventsServer::new();
    let sample_time = OnceLock::new();
    server.register_check(
        Descriptor::typed::<JsonObject, JsonObject>(
            "demo.sample",
            "A sample generated by the first replay request",
            [DeliveryMode::Poll, DeliveryMode::Push],
        ),
        move |_, _, query| {
            let mut batch = CheckedBatch::new("1");
            match query.cursor.as_deref() {
                None if sample_time.get().is_none() => batch.end = "0".into(),
                None | Some("1") => {}
                Some("0") => {
                    let time = *sample_time.get_or_init(chrono::Utc::now);
                    if query.age_floor.is_some_and(|floor| time < floor) {
                        batch.start = Some("1".into());
                    } else {
                        batch.events.push(EventOccurrence::new(
                            "sample",
                            "demo.sample",
                            time,
                            JsonObject::new(),
                        ));
                    }
                }
                _ => return ready(Err(EventsError::InvalidParams("unknown cursor".into()))),
            }
            ready(Ok(batch))
        },
    )?;
    Server(server).serve(stdio()).await?.waiting().await?;
    Ok(())
}
